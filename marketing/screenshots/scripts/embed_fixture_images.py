#!/usr/bin/env python3
"""mobile/integration_test/assets/fixtures/*.jpg -> fixture_images.g.dart

Fotoğraflar uygulamanın pubspec asset listesine eklenmesin (üretim paketini
şişirmesin) diye ekran görüntüsü düzeneğine base64 olarak gömülür.
Fotoğraf eklediğinde/değiştirdiğinde bu betiği yeniden çalıştır.
"""
import base64, pathlib
root = pathlib.Path(__file__).resolve().parents[3] / 'mobile' / 'integration_test'
src = root / 'assets' / 'fixtures'
out = root / 'screenshots' / 'fixture_images.g.dart'
lines = ['// GENERATED by marketing/screenshots/scripts/embed_fixture_images.py — elle düzenleme.',
         '// ignore_for_file: lines_longer_than_80_chars', '',
         'const Map<String, String> fixtureImagesBase64 = {']
for f in sorted(src.glob('*.jpg')):
    lines.append(f"  '{f.stem}': '{base64.b64encode(f.read_bytes()).decode()}',")
lines.append('};')
out.write_text('\n'.join(lines) + '\n')
print('wrote', out, out.stat().st_size)
